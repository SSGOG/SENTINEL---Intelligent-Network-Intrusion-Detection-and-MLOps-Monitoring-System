# -*- coding: utf-8 -*-
"""Preprocess the CIC-IDS2017 flow CSVs.

- Loads the dataset manifest generated by ``data_validation.py``.
- Concatenates all primary CSV files.
- Converts the ``Label`` column into a binary target (benign vs malicious).
- Performs a deterministic train/validation/test split (seed=42).
- Handles infinite values, imputes missing data with median, scales features.
- Saves NumPy ``.npy`` arrays for features and target, a JSON schema describing the feature order,
  and a bundled preprocessor (imputer + scaler) for reuse in training and serving.
"""

import json
import logging
import os
from pathlib import Path
from typing import List

import joblib
import numpy as np
import pandas as pd
from sklearn.impute import SimpleImputer
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler

logging.basicConfig(level=logging.INFO, format="%(asctime)s [%(levelname)s] %(message)s")
logger = logging.getLogger(__name__)

# Paths – keep them relative to the repository root for reproducibility
MANIFEST_PATH = Path("reports/data_quality/dataset_manifest.json")
OUTPUT_DIR = Path("data/processed")
OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
SCHEMA_PATH = OUTPUT_DIR / "feature_schema.json"
BUNDLE_PATH = Path("models/preprocessor_bundle.joblib")


def load_all_primary_csvs() -> pd.DataFrame:
    """Read every CSV listed under the ``primary_machine_learning_csv`` key.

    The manifest contains a list of dictionaries with ``filename`` and other metadata.
    We rely on the ``filename`` to locate the file inside the ``MachineLearningCSV/MachineLearningCVE`` directory.
    """
    with open(MANIFEST_PATH, "r", encoding="utf-8") as f:
        manifest = json.load(f)
    records = manifest.get("primary_machine_learning_csv", [])
    dfs: List[pd.DataFrame] = []
    for rec in records:
        csv_path = Path("MachineLearningCSV/MachineLearningCVE") / rec["filename"]
        logger.info(f"Loading {csv_path}")
        df = pd.read_csv(csv_path, low_memory=False)
        df.columns = [c.strip() for c in df.columns]
        dfs.append(df)
    full_df = pd.concat(dfs, ignore_index=True)
    logger.info(f"Combined dataframe shape: {full_df.shape}")
    return full_df


def binary_label(series: pd.Series) -> pd.Series:
    """Map the original multi‑class labels to ``benign`` (0) or ``malicious`` (1)."""
    benign_set = {"BENIGN", "Benign", "benign"}
    return series.apply(lambda x: 0 if str(x).strip() in benign_set else 1)


def build_feature_schema(columns: List[str]) -> dict:
    """Create a minimal schema – just the ordered column names for now.
    Future extensions (scaling, encoding) can be added here without breaking downstream code.
    """
    return {"feature_order": columns}


def main():
    df = load_all_primary_csvs()
    if "Label" not in df.columns:
        raise RuntimeError("Expected a 'Label' column in the CSV files.")
    # Ensure clean column names
    df.columns = [c.strip() for c in df.columns]
    y = binary_label(df["Label"]).astype(np.int8)
    # Drop label and keep only numeric columns for baseline model
    X = df.drop(columns=["Label"]).select_dtypes(include=[np.number])
    logger.info(f"Feature matrix shape after numeric selection: {X.shape}")
    # Replace infinities with NaN
    X.replace([np.inf, -np.inf], np.nan, inplace=True)
    # Deterministic split (80/10/10)
    X_train, X_tmp, y_train, y_tmp = train_test_split(
        X.values, y.values, test_size=0.2, random_state=42, stratify=y
    )
    X_val, X_test, y_val, y_test = train_test_split(
        X_tmp, y_tmp, test_size=0.5, random_state=42, stratify=y_tmp
    )
    # Fit imputer and scaler on training data
    imputer = SimpleImputer(strategy="median")
    X_train_imp = imputer.fit_transform(X_train)
    scaler = StandardScaler()
    X_train_scaled = scaler.fit_transform(X_train_imp)
    # Bundle preprocessing objects
    schema = build_feature_schema(list(X.columns))
    SCHEMA_PATH.write_text(json.dumps(schema, indent=2), encoding="utf-8")
    logger.info(f"Feature schema written to {SCHEMA_PATH}")
    preprocessor_bundle = {
        "imputer": imputer,
        "scaler": scaler,
        "feature_names": schema["feature_order"]
    }
    os.makedirs(BUNDLE_PATH.parent, exist_ok=True)
    joblib.dump(preprocessor_bundle, BUNDLE_PATH)
    logger.info(f"Preprocessor bundle saved to {BUNDLE_PATH}")
    # Transform validation and test sets using the fitted bundle
    def transform(arr):
        return scaler.transform(imputer.transform(arr))

    X_val_scaled = transform(X_val)
    X_test_scaled = transform(X_test)
    # Save processed arrays
    np.save(OUTPUT_DIR / "X_train.npy", X_train_scaled)
    np.save(OUTPUT_DIR / "X_val.npy", X_val_scaled)
    np.save(OUTPUT_DIR / "X_test.npy", X_test_scaled)
    np.save(OUTPUT_DIR / "y_train.npy", y_train)
    np.save(OUTPUT_DIR / "y_val.npy", y_val)
    np.save(OUTPUT_DIR / "y_test.npy", y_test)
    logger.info("Saved train/validation/test NumPy arrays.")

if __name__ == "__main__":
    main()
