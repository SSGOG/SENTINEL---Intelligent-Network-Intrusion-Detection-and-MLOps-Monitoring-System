# Create preprocessor bundle for Sentinel API
"""
This script loads the training feature matrix generated by preprocess.py and fits the
required preprocessing objects (SimpleImputer and StandardScaler). It then stores
a bundle containing these objects together with the ordered feature names.
The FastAPI service (`api.py`) expects the bundle at:
    models/preprocessor_bundle.joblib
The bundle format is a dict with keys:
    - "imputer": fitted SimpleImputer
    - "scaler": fitted StandardScaler
    - "feature_names": list of feature column names in the order they appear in the
      training matrix
"""

import json
import joblib
from pathlib import Path
import numpy as np
import pandas as pd

from sklearn.impute import SimpleImputer
from sklearn.preprocessing import StandardScaler

# Paths (relative to repository root)
DATA_DIR = Path("data/processed")
MODELS_DIR = Path("models")
MODELS_DIR.mkdir(parents=True, exist_ok=True)

# Load training data
X_train_path = DATA_DIR / "X_train.npy"
if not X_train_path.exists():
    raise FileNotFoundError(f"Training features not found at {X_train_path}. Run preprocess.py first.")

# Load feature schema to get column ordering
schema_path = DATA_DIR / "feature_schema.json"
with open(schema_path, "r", encoding="utf-8") as f:
    schema = json.load(f)
feature_names = schema.get("feature_order") or schema.get("feature_names")
if not feature_names:
    raise KeyError("Feature order not found in schema JSON.")

# Load the numpy array and reconstruct a DataFrame for consistency
X_train = np.load(X_train_path)
X_train_df = pd.DataFrame(X_train, columns=feature_names)

# Fit imputer (median) and scaler (standard)
imputer = SimpleImputer(strategy="median")
X_imputed = imputer.fit_transform(X_train_df)

scaler = StandardScaler()
X_scaled = scaler.fit_transform(X_imputed)

# Save the bundle
bundle = {
    "imputer": imputer,
    "scaler": scaler,
    "feature_names": feature_names,
}
bundle_path = MODELS_DIR / "preprocessor_bundle.joblib"
joblib.dump(bundle, bundle_path)
print(f"Preprocessor bundle saved to {bundle_path}")
